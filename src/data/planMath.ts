function cnNum(n: number): string {
  return ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九'][n] ?? String(n)
}
function cnResult(n: number): string {
  if (n < 10) return cnNum(n)
  if (n < 20) return '十' + (n % 10 ? cnNum(n % 10) : '')
  const t = Math.floor(n / 10)
  return cnNum(t) + '十' + (n % 10 ? cnNum(n % 10) : '')
}

