/** 异分母分数加减 */
export const wFracAddDiff = (count = 8) => (): Question[] => {
  const qs: Question[] = []
  const used = new Set<string>()
  while (qs.length < count) {
    const d1 = pick([2, 3, 4, 5, 6])
    let d2 = pick([2, 3, 4, 5, 6, 8, 10, 12])
    if (d2 === d1) d2 = d1 * 2
    const a = 1 + rnd(d1 - 1)
    const b = 1 + rnd(d2 - 1)
    const isAdd = rnd(2) === 0
    const key = `${a}/${d1}${isAdd ? '+' : '-'}${b}/${d2}`
    if (used.has(key)) continue
    used.add(key)
    const lcm = (d1 * d2) / gcd(d1, d2)
    const n1 = a * (lcm / d1)
    const n2 = b * (lcm / d2)
    if (!isAdd && n1 <= n2) continue
    const num = isAdd ? n1 + n2 : n1 - n2
    const g = gcd(num, lcm)
    const ans = `${num / g}/${lcm / g}`
    const pool = new Set<string>([ans])
    for (const c of [`${num}/${lcm}`, `${num + 1}/${lcm}`, `${num}/${lcm + 1}`, `${Math.max(1, num - 1)}/${lcm}`]) {
      if (pool.size >= 4) break
      const [n, d] = c.split('/').map(Number)
      if (n * lcm !== num * d && ![...pool].some((v) => {
        const [pn, pd] = v.split('/').map(Number)
        return pn * d === n * pd
      })) pool.add(c)
    }
    let k = 2
    while (pool.size < 4) pool.add(`${num + k++}/${lcm}`)
    qs.push({
      id: qid(), prompt: '先通分再计算', big: `${a}/${d1} ${isAdd ? '+' : '−'} ${b}/${d2} = ?`,
      options: shuffle([...pool]), answer: ans,
      explain: `通分成分母 ${lcm}：${n1}/${lcm} ${isAdd ? '+' : '−'} ${n2}/${lcm} = ${ans}。`,
    })
  }
  return qs
}
function gcd(x: number, y: number): number {
  return y === 0 ? x : gcd(y, x % y)
}

/** 约分 */
export const wSimplify = (count = 10) => (): Question[] =>
  Array.from({ length: count }, () => {
    const g = pick([2, 3, 4, 5])
    const n = 1 + rnd(5)
    const d = n + 1 + rnd(5)
    const divisor = gcd(n, d)
    const ans = `${n / divisor}/${d / divisor}`
    const pool = new Set<string>([ans])
    for (const c of [`${n + 1}/${d}`, `${n}/${d + 1}`, `${n}/${d + 2}`]) {
      if (pool.size >= 4) break
      pool.add(c)
    }
    let k = 2
    while (pool.size < 4) pool.add(`${n + k++}/${d}`)
    return {
      id: qid(), prompt: '约分成最简分数', big: `${n * g}/${d * g} = ?`,
      options: shuffle([...pool]), answer: ans,
      explain: `分子分母的最大公因数是 ${g * divisor}，同时除以它：${n * g}÷${g * divisor}=${n / divisor}，${d * g}÷${g * divisor}=${d / divisor}，所以最简分数是 ${ans}。`,
    }
  })

