let seq = 0
const qid = () => `qpm${Date.now().toString(36)}-${seq++}`
const rnd = (n: number) => Math.floor(Math.random() * n)
const pick = <T,>(arr: T[]): T => arr[rnd(arr.length)]
function shuffle<T>(arr: T[]): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = rnd(i + 1)
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** 数值选项：答案 + 扰动项，去重 */
function numOpts(ans: number, fixed?: number): string[] {
  const fmt = (v: number) => (fixed != null ? v.toFixed(fixed) : String(v))
  const set = new Set<string>([fmt(ans)])
  const cands = shuffle([ans + 1, ans - 1, ans + 2, ans - 2, ans + 10, ans - 10, ans + 5, ans * 2])
  for (const c of cands) {
    if (set.size >= 4) break
    if (c < 0 || (fixed == null && !Number.isInteger(c))) continue
    set.add(fmt(c))
  }
  let k = 3
  while (set.size < 4) {
    set.add(fmt(ans + k))
    k += 3
  }
  return shuffle([...set])
}

